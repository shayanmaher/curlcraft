import { ParsedCurl, GenerateOptions, GeneratedCode } from '../types.js';
import { toPascalCase } from '../inference/typeInference.js';

function deriveSnakeName(parsed: ParsedCurl): string {
  const parts = parsed.pathname
    .split('/')
    .filter(Boolean)
    .map((p) => p.replace(/[^a-zA-Z0-9]/g, '_').toLowerCase());

  if (parts.length === 0) {
    return `${parsed.method.toLowerCase()}_root`;
  }

  return `${parsed.method.toLowerCase()}_${parts.join('_')}`;
}

export function generatePython(parsed: ParsedCurl, options: GenerateOptions = {}): GeneratedCode {
  const funcName = deriveSnakeName(parsed);
  const pascalName = toPascalCase(funcName);
  const lines: string[] = [];

  lines.push(
    '"""',
    'Auto-generated by CurlCraft',
    `Endpoint: ${parsed.method} ${parsed.pathname}`,
    `Original Host: ${parsed.baseUrl}`,
    '"""',
    'from typing import Optional, Dict, Any',
    'import httpx',
    ''
  );

  // Generate request model if JSON body exists
  if (parsed.jsonBody && typeof parsed.jsonBody === 'object') {
    lines.push('from pydantic import BaseModel', '');
    lines.push(`class ${pascalName}Request(BaseModel):`);
    for (const [key, val] of Object.entries(parsed.jsonBody)) {
      const typeStr =
        typeof val === 'number'
          ? 'float'
          : typeof val === 'boolean'
          ? 'bool'
          : typeof val === 'string'
          ? 'str'
          : 'Any';
      lines.push(`    ${key}: ${typeStr}`);
    }
    lines.push('', '');
  }

  // Function signature
  const params: string[] = [];
  if (parsed.jsonBody) {
    params.push(`payload: ${pascalName}Request`);
  } else if (parsed.body) {
    params.push(`payload: str`);
  }

  if (Object.keys(parsed.queryParams).length > 0) {
    params.push(`query_params: Optional[Dict[str, Any]] = None`);
  }

  params.push(`base_url: str = "${parsed.baseUrl}"`);

  if (parsed.auth?.type === 'bearer') {
    params.push(`auth_token: Optional[str] = "${parsed.auth.token ?? ''}"`);
  } else if (parsed.auth?.type === 'basic') {
    params.push(`username: Optional[str] = "${parsed.auth.username ?? ''}"`);
    params.push(`password: Optional[str] = "${parsed.auth.password ?? ''}"`);
  } else if (parsed.auth?.type === 'custom') {
    params.push(`api_key: Optional[str] = "${parsed.auth.headerValue ?? ''}"`);
  }

  params.push(`headers: Optional[Dict[str, str]] = None`);

  lines.push(`def ${funcName}(`);
  lines.push(`    ${params.join(',\n    ')}`);
  lines.push(`) -> Dict[str, Any]:`);

  // URL formatting
  lines.push(`    url = f"{base_url.rstrip('/')}${parsed.pathname}"`);
  lines.push(`    req_headers = {`);
  for (const [k, v] of Object.entries(parsed.headers)) {
    if (k.toLowerCase() !== 'authorization') {
      lines.push(`        "${k}": "${v.replace(/"/g, '\\"')}",`);
    }
  }
  lines.push(`    }`);
  lines.push(`    if headers:`);
  lines.push(`        req_headers.update(headers)`);
  lines.push('');

  if (parsed.auth?.type === 'bearer') {
    lines.push(`    if auth_token:`);
    lines.push(`        req_headers["Authorization"] = f"Bearer {auth_token}"`);
    lines.push('');
  } else if (parsed.auth?.type === 'custom' && parsed.auth.headerKey) {
    lines.push(`    if api_key:`);
    lines.push(`        req_headers["${parsed.auth.headerKey}"] = api_key`);
    lines.push('');
  }

  lines.push(`    with httpx.Client() as client:`);
  const reqArgs: string[] = [`"${parsed.method}"`, `url`, `headers=req_headers`];
  if (Object.keys(parsed.queryParams).length > 0) {
    reqArgs.push(`params=query_params`);
  }
  if (parsed.jsonBody) {
    reqArgs.push(`json=payload.model_dump()`);
  } else if (parsed.body) {
    reqArgs.push(`content=payload`);
  }

  lines.push(`        response = client.request(${reqArgs.join(', ')})`);
  lines.push(`        response.raise_for_status()`);
  lines.push(`        return response.json()`);

  return {
    code: lines.join('\n'),
    language: 'python',
    suggestedFilename: `${funcName}.py`,
  };
}
