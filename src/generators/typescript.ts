import { ParsedCurl, GenerateOptions, GeneratedCode } from '../types.js';
import {
  generateInterfacesFromValue,
  generateZodSchemaFromValue,
  toPascalCase,
} from '../inference/typeInference.js';

function deriveFunctionName(parsed: ParsedCurl): string {
  const parts = parsed.pathname
    .split('/')
    .filter(Boolean)
    .map((p) => p.replace(/[^a-zA-Z0-9]/g, ''));

  if (parts.length === 0) {
    return `${parsed.method.toLowerCase()}Root`;
  }

  const endpointName = parts
    .map((p, idx) => (idx === 0 ? p.toLowerCase() : toPascalCase(p)))
    .join('');

  return `${parsed.method.toLowerCase()}${toPascalCase(endpointName)}`;
}

export function generateTypeScript(parsed: ParsedCurl, options: GenerateOptions = {}): GeneratedCode {
  const funcName = options.functionName || deriveFunctionName(parsed);
  const clientName = options.clientName || `${toPascalCase(funcName)}Client`;
  const pascalName = toPascalCase(funcName);

  const lines: string[] = [];

  // Comments & Metadata Header
  lines.push('/**',
    ` * Auto-generated by CurlCraft`,
    ` * Endpoint: ${parsed.method} ${parsed.pathname}`,
    ` * Original Host: ${parsed.baseUrl}`,
    ` */`,
    ''
  );

  // Optional Imports
  if (options.includeZod) {
    lines.push(`import { z } from 'zod';`);
  }
  if (options.reactQuery) {
    lines.push(`import { useQuery, useMutation, type UseQueryOptions, type UseMutationOptions } from '@tanstack/react-query';`);
  }
  if (options.includeZod || options.reactQuery) {
    lines.push('');
  }

  // Generate Request Body Type
  let requestBodyType = 'Record<string, unknown>';

  if (parsed.jsonBody) {
    requestBodyType = `${pascalName}Request`;
    const interfaceDef = generateInterfacesFromValue(parsed.jsonBody, requestBodyType);
    lines.push(interfaceDef, '');

    if (options.includeZod) {
      const zodDef = generateZodSchemaFromValue(parsed.jsonBody, `${requestBodyType}Schema`);
      lines.push(zodDef, '');
    }
  }

  // Generate Query Params Type
  const hasQueryParams = Object.keys(parsed.queryParams).length > 0;
  let queryParamsType = '';
  if (hasQueryParams) {
    queryParamsType = `${pascalName}QueryParams`;
    lines.push(`export interface ${queryParamsType} {`);
    for (const [key, val] of Object.entries(parsed.queryParams)) {
      lines.push(`  ${key}?: string | number | boolean; // Example: "${val}"`);
    }
    lines.push(`}\n`);
  }

  // Generate Response Type (Probed or Placeholder)
  const responseTypeName = `${pascalName}Response`;
  if (options.probedResponse && typeof options.probedResponse === 'object') {
    lines.push(`// Inferred from live server response via --probe`);
    const responseInterfaceDef = generateInterfacesFromValue(options.probedResponse, responseTypeName);
    lines.push(responseInterfaceDef, '');

    if (options.includeZod) {
      const responseZodDef = generateZodSchemaFromValue(options.probedResponse, `${responseTypeName}Schema`);
      lines.push(responseZodDef, '');
    }
  } else {
    lines.push(`export interface ${responseTypeName} {`);
    lines.push(`  [key: string]: unknown;`);
    lines.push(`}\n`);
  }

  // Client Options Interface
  lines.push(`export interface ${pascalName}Options {`);
  lines.push(`  baseUrl?: string;`);
  if (parsed.auth?.type === 'bearer') {
    lines.push(`  authToken?: string;`);
  } else if (parsed.auth?.type === 'basic') {
    lines.push(`  username?: string;`);
    lines.push(`  password?: string;`);
  } else if (parsed.auth?.type === 'custom') {
    lines.push(`  apiKey?: string;`);
  }
  lines.push(`  headers?: Record<string, string>;`);
  lines.push(`  signal?: AbortSignal;`);
  lines.push(`}\n`);

  // Build the Fetch Function
  const paramList: string[] = [];
  if (parsed.jsonBody) {
    paramList.push(`payload: ${requestBodyType}`);
  } else if (parsed.body) {
    paramList.push(`payload: string`);
  }

  if (hasQueryParams) {
    paramList.push(`query?: ${queryParamsType}`);
  }

  paramList.push(`options: ${pascalName}Options = {}`);

  lines.push(`/**`);
  lines.push(` * Execute ${parsed.method} request to ${parsed.pathname}`);
  lines.push(` */`);
  lines.push(`export async function ${funcName}(`);
  lines.push(`  ${paramList.join(',\n  ')}`);
  lines.push(`): Promise<${responseTypeName}> {`);

  // Construct URL
  lines.push(`  const baseUrl = (options.baseUrl ?? "${parsed.baseUrl}").replace(/\\/+$/, '');`);
  lines.push(`  const url = new URL(\`\${baseUrl}${parsed.pathname}\`);`);

  if (hasQueryParams) {
    lines.push('');
    lines.push(`  if (query) {`);
    lines.push(`    Object.entries(query).forEach(([k, v]) => {`);
    lines.push(`      if (v !== undefined && v !== null) {`);
    lines.push(`        url.searchParams.set(k, String(v));`);
    lines.push(`      }`);
    lines.push(`    });`);
    lines.push(`  }`);
  }

  lines.push('');
  lines.push(`  const headers: Record<string, string> = {`);

  // Include non-auth headers from curl
  for (const [k, v] of Object.entries(parsed.headers)) {
    if (k.toLowerCase() !== 'authorization') {
      lines.push(`    "${k}": "${v.replace(/"/g, '\\"')}",`);
    }
  }

  lines.push(`    ...options.headers,`);
  lines.push(`  };`);
  lines.push('');

  // Handle Auth injection
  if (parsed.auth?.type === 'bearer') {
    lines.push(`  const token = options.authToken ?? "${parsed.auth.token ?? ''}";`);
    lines.push(`  if (token) {`);
    lines.push(`    headers['Authorization'] = \`Bearer \${token}\`;`);
    lines.push(`  }`);
    lines.push('');
  } else if (parsed.auth?.type === 'basic') {
    lines.push(`  const username = options.username ?? "${parsed.auth.username ?? ''}";`);
    lines.push(`  const password = options.password ?? "${parsed.auth.password ?? ''}";`);
    lines.push(`  if (username || password) {`);
    lines.push(`    const encoded = typeof btoa !== 'undefined' ? btoa(\`\${username}:\${password}\`) : Buffer.from(\`\${username}:\${password}\`).toString('base64');`);
    lines.push(`    headers['Authorization'] = \`Basic \${encoded}\`;`);
    lines.push(`  }`);
    lines.push('');
  } else if (parsed.auth?.type === 'custom' && parsed.auth.headerKey) {
    lines.push(`  const apiKey = options.apiKey ?? "${parsed.auth.headerValue ?? ''}";`);
    lines.push(`  if (apiKey) {`);
    lines.push(`    headers['${parsed.auth.headerKey}'] = apiKey;`);
    lines.push(`  }`);
    lines.push('');
  }

  // Fetch invocation
  lines.push(`  const res = await fetch(url.toString(), {`);
  lines.push(`    method: "${parsed.method}",`);
  lines.push(`    headers,`);
  if (parsed.jsonBody) {
    lines.push(`    body: JSON.stringify(payload),`);
  } else if (parsed.body) {
    lines.push(`    body: payload,`);
  }
  lines.push(`    signal: options.signal,`);
  lines.push(`  });`);
  lines.push('');

  // Error checking
  lines.push(`  if (!res.ok) {`);
  lines.push(`    const errorText = await res.text();`);
  lines.push(`    throw new Error(\`Request to \${url} failed with status \${res.status}: \${errorText}\`);`);
  lines.push(`  }`);
  lines.push('');
  lines.push(`  const contentType = res.headers.get('content-type');`);
  lines.push(`  if (contentType && contentType.includes('application/json')) {`);
  lines.push(`    return (await res.json()) as ${responseTypeName};`);
  lines.push(`  }`);
  lines.push('');
  lines.push(`  return { data: await res.text() } as unknown as ${responseTypeName};`);
  lines.push(`}`);

  // Class wrapper
  if (options.format === 'class') {
    lines.push('');
    lines.push(`export class ${clientName} {`);
    lines.push(`  constructor(private defaultOptions: ${pascalName}Options = {}) {}`);
    lines.push('');
    lines.push(`  async ${funcName}(`);
    if (parsed.jsonBody) {
      lines.push(`    payload: ${requestBodyType},`);
    } else if (parsed.body) {
      lines.push(`    payload: string,`);
    }
    if (hasQueryParams) {
      lines.push(`    query?: ${queryParamsType},`);
    }
    lines.push(`    options: ${pascalName}Options = {}`);
    lines.push(`  ): Promise<${responseTypeName}> {`);

    const callArgs: string[] = [];
    if (parsed.jsonBody || parsed.body) callArgs.push('payload');
    if (hasQueryParams) callArgs.push('query');
    callArgs.push('{ ...this.defaultOptions, ...options }');

    lines.push(`    return ${funcName}(${callArgs.join(', ')});`);
    lines.push(`  }`);
    lines.push(`}`);
  }

  // React Query Hooks
  if (options.reactQuery) {
    lines.push('');
    lines.push(`// --- TanStack React Query Hooks ---`);

    const isGet = parsed.method.toUpperCase() === 'GET';

    if (isGet) {
      const hookName = `use${pascalName}Query`;
      lines.push(`export function ${hookName}(`);
      if (hasQueryParams) {
        lines.push(`  query?: ${queryParamsType},`);
      }
      lines.push(`  options?: ${pascalName}Options,`);
      lines.push(`  queryOptions?: Omit<UseQueryOptions<${responseTypeName}, Error>, 'queryKey' | 'queryFn'>`);
      lines.push(`) {`);
      const keyParts = [`"${parsed.pathname}"`];
      if (hasQueryParams) keyParts.push('query');
      lines.push(`  return useQuery({`);
      lines.push(`    queryKey: [${keyParts.join(', ')}],`);
      const fetchCallArgs: string[] = [];
      if (hasQueryParams) fetchCallArgs.push('query');
      fetchCallArgs.push('{ ...options, signal }');
      lines.push(`    queryFn: ({ signal }) => ${funcName}(${fetchCallArgs.join(', ')}),`);
      lines.push(`    ...queryOptions,`);
      lines.push(`  });`);
      lines.push(`}`);
    } else {
      const hookName = `use${pascalName}Mutation`;
      const mutationVariables: string[] = [];
      if (parsed.jsonBody) {
        mutationVariables.push(`payload: ${requestBodyType}`);
      } else if (parsed.body) {
        mutationVariables.push(`payload: string`);
      }
      if (hasQueryParams) {
        mutationVariables.push(`query?: ${queryParamsType}`);
      }

      const varTypeStr = mutationVariables.length > 0 ? `{ ${mutationVariables.join('; ')} }` : 'void';

      lines.push(`export function ${hookName}(`);
      lines.push(`  options?: ${pascalName}Options,`);
      lines.push(`  mutationOptions?: UseMutationOptions<${responseTypeName}, Error, ${varTypeStr}>`);
      lines.push(`) {`);
      lines.push(`  return useMutation({`);
      if (mutationVariables.length > 0) {
        const destructureKeys = mutationVariables.map((v) => v.split(':')[0].trim()).join(', ');
        const callArgs = [destructureKeys, 'options'].filter(Boolean);
        lines.push(`    mutationFn: ({ ${destructureKeys} }: ${varTypeStr}) => ${funcName}(${callArgs.join(', ')}),`);
      } else {
        lines.push(`    mutationFn: () => ${funcName}(options),`);
      }
      lines.push(`    ...mutationOptions,`);
      lines.push(`  });`);
      lines.push(`}`);
    }
  }

  return {
    code: lines.join('\n'),
    language: 'typescript',
    suggestedFilename: `${funcName}.ts`,
  };
}
